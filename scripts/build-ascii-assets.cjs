// Classic scripts and data URLs also work when index.html is opened from disk.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const dataUrl = (file, type) => `data:${type};base64,${fs.readFileSync(path.join(root, file)).toString('base64')}`;
const art = Object.fromEntries(['cap', 'diploma', 'arrow', 'question', 'logo'].map(shape => [shape, dataUrl(`assets/matrix/${shape === 'logo' ? 'wordmark' : shape}.svg`, 'image/svg+xml')]));
const assets = { font: dataUrl('assets/fonts/recursive-mono.woff2', 'font/woff2'), art };
fs.writeFileSync(path.join(root, 'ascii-assets.js'), `/* Generated by npm run build:assets. Source artwork and font license live in assets/. */\nwindow.AsciiAssets = ${JSON.stringify(assets)};\n`);
console.log('Built embedded ASCII artwork and font.');
